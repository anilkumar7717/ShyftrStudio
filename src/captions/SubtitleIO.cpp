static QString two(qint64 v) { return QString("%1").arg(v, 2, 10, QChar('0')); }

QString srtTime(TimeUs t)
{
    t = std::max<TimeUs>(0, t);
    const qint64 ms = (t + 500) / 1000;
    return QString("%1:%2:%3,%4").arg(two(ms / 3600000), two((ms / 60000) % 60), two((ms / 1000) % 60))
        .arg(ms % 1000, 3, 10, QChar('0'));
}

QString vttTime(TimeUs t)
{
    QString s = srtTime(t);
    s[8] = '.';
    return s;
}

QString assTime(TimeUs t)
{
    t = std::max<TimeUs>(0, t);
    const qint64 cs = (t + 5000) / 10000;
    return QString("%1:%2:%3.%4").arg(cs / 360000).arg(two((cs / 6000) % 60), two((cs / 100) % 60), two(cs % 100));
}

QString assColor(const QColor &c)
{
    // &HAABBGGRR, alpha 00 = opaque
    return QString("&H%1%2%3%4")
        .arg(255 - c.alpha(), 2, 16, QChar('0'))
        .arg(c.blue(), 2, 16, QChar('0'))
        .arg(c.green(), 2, 16, QChar('0'))
        .arg(c.red(), 2, 16, QChar('0'))
        .toUpper();
}

static QStringList cueWords(const CueInstance &c, const CaptionStyle &s)
{
    QStringList out;
    for (const auto &w : c.words)
        out << (s.uppercase ? w.text.toUpper() : w.text);
    return out;
}

static QString cueLines(const CueInstance &c, const CaptionStyle &s, const QString &sep)
{
    const QStringList words = cueWords(c, s);
    return LineBreaker::joinLines(words, LineBreaker::breakLines(words, s.maxWordsPerLine, s.maxCharsPerLine, s.maxLines),
                                  sep);
}

QString toSrt(const QVector<CueInstance> &cues, const CaptionStyle &s, TimeUs offset)
{
    QString out;
    int n = 1;
    for (const auto &c : cues) {
        out += QString::number(n++) + "\n";
        out += srtTime(c.start - offset) + " --> " + srtTime(c.end - offset) + "\n";
        out += cueLines(c, s, "\n") + "\n\n";
    }
    return out;
}

QString toVtt(const QVector<CueInstance> &cues, const CaptionStyle &s, const QVector<Speaker> &speakers,
              bool wordTimestamps, TimeUs offset)
{
    QString out = "WEBVTT\n\n";
    for (const auto &c : cues) {
        out += vttTime(c.start - offset) + " --> " + vttTime(c.end - offset) + "\n";
        QString speakerTag;
        for (const auto &sp : speakers)
            if (sp.id == c.speaker)
                speakerTag = "<v " + sp.name + ">";
        if (wordTimestamps) {
            const QStringList words = cueWords(c, s);
            const auto lines = LineBreaker::breakLines(words, s.maxWordsPerLine, s.maxCharsPerLine, s.maxLines);
            QStringList lineTexts;
            for (const auto &l : lines) {
                QStringList parts;
                for (int i : l)
                    parts << (i == 0 ? words[i] : "<" + vttTime(c.words[i].start - offset) + ">" + words[i]);
                lineTexts << parts.join(' ');
            }
            out += speakerTag + lineTexts.join("\n") + "\n\n";
        } else {
            out += speakerTag + cueLines(c, s, "\n") + "\n\n";
        }
    }
    return out;
}

QString toAss(const QVector<CueInstance> &cues, const CaptionStyle &s, int width, int height, TimeUs offset)
{
    const QRectF safe = SafeArea::forFrame(width, height);
    int alignment = 2;
    if (s.anchor == "middle")
        alignment = 5;
    else if (s.anchor == "top")
        alignment = 8;
    if (s.align == "left")
        alignment -= 1;
    else if (s.align == "right")
        alignment += 1;
    const int fontSize = int(std::lround(s.sizePct * height));
    const int marginV = s.anchor == "top" ? int(safe.top()) : int(height - safe.bottom() + s.offsetYPct * height);
    const int dx = int(std::lround(s.offsetXPct * width)); // horizontal drag offset
    const int marginL = std::max(0, int(safe.left()) + dx);
    const int marginR = std::max(0, int(width - safe.right()) - dx);
    const bool box = s.boxMode != "none";
    const bool karaoke = s.wordEffect == "karaoke" || s.wordEffect == "highlight";

    QString out;
    out += "[Script Info]\n; Generated by Shyftr Studio\nScriptType: v4.00+\nWrapStyle: 2\nScaledBorderAndShadow: yes\n";
    out += QString("PlayResX: %1\nPlayResY: %2\n\n").arg(width).arg(height);
    out += "[V4+ Styles]\n";
    out += "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, "
           "Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, "
           "MarginR, MarginV, Encoding\n";
    const QColor primary = karaoke ? s.activeColor : s.textColor;
    const QColor secondary = s.textColor;
    out += QString("Style: Default,%1,%2,%3,%4,%5,%6,%7,%8,0,0,100,100,%9,0,%10,%11,%12,%13,%14,%15,%16,1\n")
               .arg(s.fontFamilies.value(0, "Arial"))
               .arg(fontSize)
               .arg(assColor(primary), assColor(secondary), assColor(box ? s.boxColor : s.outlineColor),
                    assColor(box ? s.boxColor : s.shadowColor))
               .arg(s.fontWeight >= 600 ? -1 : 0)
               .arg(s.italic ? -1 : 0)
               .arg(QString::number(s.letterSpacingPct * fontSize / 100.0, 'f', 1))
               .arg(box ? 3 : 1)
               .arg(QString::number(box ? s.boxPaddingPct * fontSize * 0.5 : s.outlineWidthPct * fontSize, 'f', 1))
               .arg(QString::number(s.shadowColor.alpha() > 0 ? s.shadowOffsetPct * fontSize : 0, 'f', 1))
               .arg(alignment)
               .arg(marginL)
               .arg(marginR)
               .arg(std::max(0, marginV));
    out += "\n[Events]\nFormat: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text\n";

    for (const auto &c : cues) {
        const QStringList words = cueWords(c, s);
        const auto lines = LineBreaker::breakLines(words, s.maxWordsPerLine, s.maxCharsPerLine, s.maxLines);
        QString text;
        QString fade;
        if (s.entry == "fade" || s.exit == "fade")
            fade = QString("{\\fad(%1,%2)}").arg(s.entry == "fade" ? s.animMs : 0).arg(s.exit == "fade" ? s.animMs : 0);
        TimeUs cursor = c.start;
        for (int li = 0; li < lines.size(); ++li) {
            if (li)
                text += "\\N";
            for (int k = 0; k < lines[li].size(); ++k) {
                const int wi = lines[li][k];
                QString word = words[wi];
                word.replace('{', '(').replace('}', ')');
                if (karaoke) {
                    // gap before the word, then the word itself
                    const TimeUs gap = c.words[wi].start - cursor;
                    if (gap > 10000)
                        text += QString("{\\k%1}").arg(gap / 10000);
                    const TimeUs dur = std::max<TimeUs>(10000, c.words[wi].end - c.words[wi].start);
                    text += QString("{\\k%1}").arg(dur / 10000);
                    cursor = c.words[wi].start + dur;
                    if (s.wordEffect == "karaoke")
                        text.replace(text.lastIndexOf("\\k"), 2, "\\kf");
                }
                text += word;
                if (k + 1 < lines[li].size())
                    text += " ";
            }
        }
        out += QString("Dialogue: 0,%1,%2,Default,,0,0,0,,%3%4\n")
                   .arg(assTime(c.start - offset), assTime(c.end - offset), fade, text);
    }
    return out;
}

QString toPlainText(const QVector<CueInstance> &cues, bool withTimes)
{
    QString out;
    for (const auto &c : cues) {
        if (withTimes)
            out += "[" + formatClock(c.start) + "] ";
        out += c.text() + "\n";
    }
    return out;
}

QVector<CueInstance> clipRange(const QVector<CueInstance> &cues, TimeUs from, TimeUs to)
{
    QVector<CueInstance> out;
    for (CueInstance c : cues) {
        if (c.end <= from || c.start >= to)
            continue;
        QVector<WordInstance> words;
        for (auto w : c.words) {
            if (w.end <= from || w.start >= to)
                continue;
            w.start = std::max(w.start, from) - from;
            w.end = std::min(w.end, to) - from;
            words << w;
        }
        if (words.isEmpty())
            continue;
        c.words = words;
        c.start = std::max(c.start, from) - from;
        c.end = std::min(c.end, to) - from;
        out << c;
    }
    return out;
}

static bool parseTime(const QString &s, TimeUs *out)
{
    static const QRegularExpression re(R"(^(?:(\d+):)?(\d{1,2}):(\d{2})[,\.](\d{1,3})$)");
    const auto m = re.match(s.trimmed());
    if (!m.hasMatch())
        return false;
    const qint64 h = m.captured(1).isEmpty() ? 0 : m.captured(1).toLongLong();
    const qint64 mi = m.captured(2).toLongLong();
    const qint64 se = m.captured(3).toLongLong();
    QString frac = m.captured(4);
    while (frac.size() < 3)
        frac += '0';
    *out = ((h * 3600 + mi * 60 + se) * 1000 + frac.toLongLong()) * kUsPerMs;
    return true;
}

bool readSubtitles(const QString &textIn, Transcript &out, QString *error)
{
    QString text = textIn;
    text.replace("\r\n", "\n").replace('\r', '\n');
    if (text.startsWith(QChar(0xFEFF)))
        text.remove(0, 1);
    const QStringList blocks = text.split(QRegularExpression("\n\\s*\n"), Qt::SkipEmptyParts);
    static const QRegularExpression arrow(R"(^\s*(\S+)\s*-->\s*(\S+))");
    static const QRegularExpression tags(R"(<[^>]*>|\{\\[^}]*\})");
    out.words.clear();
    out.cues.clear();
    for (const QString &block : blocks) {
        const QStringList lines = block.split('\n');
        int i = 0;
        while (i < lines.size() && !arrow.match(lines[i]).hasMatch())
            ++i;
        if (i >= lines.size())
            continue; // header / NOTE / index-only
        const auto m = arrow.match(lines[i]);
        TimeUs s, e;
        if (!parseTime(m.captured(1), &s) || !parseTime(m.captured(2), &e) || e <= s)
            continue;
        QString body = lines.mid(i + 1).join(' ');
        body.remove(tags);
        const QStringList words = body.split(QRegularExpression("\\s+"), Qt::SkipEmptyParts);
        if (words.isEmpty())
            continue;
        int weight = 0;
        for (const QString &w : words)
            weight += w.size() + 1;
        Cue cue;
        cue.first = out.words.size();
        cue.manual = true;
        TimeUs cur = s;
        for (int k = 0; k < words.size(); ++k) {
            Word w;
            w.text = words[k];
            w.start = cur;
            w.end = k == words.size() - 1 ? e : cur + (e - s) * (words[k].size() + 1) / weight;
            w.hardBreakBefore = k == 0;
            cur = w.end;
            out.words << w;
        }
        cue.last = out.words.size() - 1;
        if (!out.cues.isEmpty() && out.words[cue.first].start < out.words[out.cues.last().last].end) {
            // overlapping subtitles: clamp to keep the transcript monotonic
            out.words[cue.first].start = out.words[out.cues.last().last].end;
            if (out.words[cue.first].end <= out.words[cue.first].start)
                out.words[cue.first].end = out.words[cue.first].start + kUsPerMs;
        }
        out.cues << cue;
    }
    if (out.cues.isEmpty()) {
        if (error)
            *error = "No subtitles were found in the file.";
        return false;
    }
    return true;
}

bool writeTextFile(const QString &path, const QString &text, QString *error)
{
    QSaveFile f(path);
    if (!f.open(QIODevice::WriteOnly)) {
        if (error)
            *error = f.errorString();
        return false;
    }
    f.write(text.toUtf8());
    if (!f.commit()) {
        if (error)
            *error = f.errorString();
        return false;
    }
    return true;
}

